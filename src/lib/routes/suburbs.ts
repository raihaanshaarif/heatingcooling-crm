const BY_NAME = new Map(
  Object.entries(SUBURBS).map(([name, [lat, lng]]) => [name.toLowerCase(), { lat, lng }]),
);

/** Centre of a Melbourne suburb ("box hill", "Box Hill " …), or null if it isn't listed. */
export function suburbCentre(suburb: string | null | undefined): LatLng | null {
  if (!suburb) return null;
  const key = suburb.trim().toLowerCase().replace(/\s+/g, " ").replace(/^mt /, "mount ");
  return BY_NAME.get(key) ?? null;
}

